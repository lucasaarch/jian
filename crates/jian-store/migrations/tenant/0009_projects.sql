-- Projects become what they are in Claude or ChatGPT: a folder made in the panel that groups
-- conversations, files (knowledge) and instructions. A repository is an optional attachment, any
-- number of them; it no longer defines the project. A project is seen the way an agent is.

-- Projects made before this had no owner-only mode: every member saw them. They keep that.
ALTER TABLE projects
    ADD COLUMN description text NOT NULL DEFAULT '',
    ADD COLUMN icon text,
    ADD COLUMN color text,
    ADD COLUMN visibility text NOT NULL DEFAULT 'workspace'
        CHECK (visibility IN ('private', 'members', 'workspace'));
-- A new project says its own: the default served only the rows that were already there.
ALTER TABLE projects ALTER COLUMN visibility DROP DEFAULT;

-- Who may see a project whose visibility is `members`, besides its creator.
CREATE TABLE project_viewers (
    project_id text NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    account_id text NOT NULL,
    PRIMARY KEY (project_id, account_id)
);
CREATE INDEX project_viewers_account ON project_viewers (account_id);

-- A repository attached to a project. `seq` is the order they were attached in.
CREATE TABLE project_repositories (
    id text PRIMARY KEY,
    seq bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
    project_id text NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    url text NOT NULL CHECK (btrim(url) <> ''),
    -- Null: whatever the repository's own default is.
    default_branch text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, url)
);

-- The single repository a project could have becomes its first attached one.
INSERT INTO project_repositories (id, project_id, url, created_at)
SELECT 'rep_' || md5(id || ':' || repository_url), id, btrim(repository_url), created_at
FROM projects
WHERE repository_url IS NOT NULL AND btrim(repository_url) <> '';

ALTER TABLE projects DROP COLUMN repository_url;

-- A file of a project's knowledge. The bytes are not here: `storage_key` is the name the blob
-- store gave them, generated by the gateway and never taken from `name`, which is only a label.
-- `size_bytes` of every row is what the tenant's disk quota counts besides the schema.
CREATE TABLE project_files (
    id text PRIMARY KEY,
    seq bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
    project_id text NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    name text NOT NULL CHECK (btrim(name) <> ''),
    size_bytes bigint NOT NULL CHECK (size_bytes >= 0),
    mime text NOT NULL,
    sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    uploaded_by text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    storage_key text NOT NULL UNIQUE
);
CREATE INDEX project_files_project ON project_files (project_id, seq);

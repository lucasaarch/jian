//! The TypeScript side of the protocol: `packages/protocol/src/index.ts` and `check.ts`.
//!
//! The types themselves are written by ts-rs, in the crate's own `export_bindings_*` tests. This
//! test runs after them (cargo runs a package's test binaries one after another) and adds what
//! ts-rs does not: the index that re-exports every generated type, and `check.ts`, where example
//! messages that Rust serialized must satisfy those types, so `tsc` fails on a shape the Rust
//! side no longer produces. `make protocol-gen` runs both and `make protocol-check` fails on any
//! difference with the committed files.

// clippy.toml excuses `#[test]` bodies, not the helpers they call.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use jian_protocol::machine::{GatewayMessage, WorkerMessage};
use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::{Value, json};

const HEADER: &str =
    "// Generated by crates/jian-protocol/tests/typescript.rs. Do not edit this file manually.\n";

fn package() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/protocol")
}

/// The example as Rust reads and writes it: a JSON that does not parse as `T` fails here, and
/// what comes back is what serde emits, which is what the TypeScript type has to describe.
fn through<T: DeserializeOwned + Serialize>(example: &Value) -> Value {
    let value: T = serde_json::from_value(example.clone()).unwrap();
    serde_json::to_value(value).unwrap()
}

fn list<T: DeserializeOwned + Serialize>(examples: &[Value]) -> String {
    let wire: Vec<Value> = examples.iter().map(through::<T>).collect();
    serde_json::to_string_pretty(&wire).unwrap()
}

#[test]
fn the_index_reexports_every_generated_type() {
    let generated = package().join("src/generated");
    let mut names: Vec<String> = fs::read_dir(&generated)
        .unwrap()
        .filter_map(|entry| {
            let name = entry.unwrap().file_name().into_string().unwrap();
            name.strip_suffix(".ts").map(str::to_owned)
        })
        .collect();
    names.sort();
    assert!(
        !names.is_empty(),
        "run the ts-rs export tests first (`make protocol-gen`)"
    );

    let mut index = String::from(HEADER);
    for name in &names {
        writeln!(
            index,
            "export type {{ {name} }} from \"./generated/{name}\";"
        )
        .unwrap();
    }
    fs::write(package().join("src/index.ts"), index).unwrap();
}

#[test]
fn examples_the_rust_side_wrote_satisfy_the_typescript_types() {
    let worker = [
        json!({ "type": "hello", "protocolVersion": 1, "workerVersion": "1.2.3", "os": "linux",
                "arch": "x86_64", "hostname": "box", "system": "Ubuntu 24.04.1 LTS",
                "capabilities": ["shell", "files"], "uiState": "unknown" }),
        json!({ "type": "output", "id": "t1", "stream": "stderr", "data": "warning" }),
        json!({ "type": "result", "id": "t1", "exitCode": 0, "stdout": "ok", "stderr": "",
                "timedOut": false, "cancelled": false }),
        json!({ "type": "result", "id": "t2", "exitCode": null, "stdout": "", "stderr": "",
                "timedOut": true, "cancelled": false }),
        json!({ "type": "result", "id": "t3", "exitCode": 0, "stdout": "", "stderr": "",
                "timedOut": false, "cancelled": false,
                "files": { "status": "done", "op": "read", "text": "hi", "mtimeMs": 1.5, "bytes": 2 } }),
        json!({ "type": "result", "id": "t4", "exitCode": 0, "stdout": "", "stderr": "",
                "timedOut": false, "cancelled": false,
                "files": { "status": "failed", "op": "write", "problem": "changed", "message": "no" } }),
        json!({ "type": "result", "id": "t5", "exitCode": 0, "stdout": "", "stderr": "",
                "timedOut": false, "cancelled": false,
                "computer": { "ok": false, "error": "denied", "code": "perm_denied",
                              "delivery": "not_delivered", "permission": "screen_recording" } }),
        json!({ "type": "forwardState", "id": "f1", "status": "open", "localPort": 41000 }),
        json!({ "type": "forwardState", "id": "f1", "status": "failed", "error": "in use" }),
        json!({ "type": "channelOpen", "forward": "f1", "channel": 7 }),
        json!({ "type": "channelClose", "channel": 7 }),
        json!({ "type": "uiState", "state": "display_asleep" }),
        json!({ "type": "ping", "nonce": 9 }),
        json!({ "type": "pong", "nonce": 9 }),
    ];
    let gateway = [
        json!({ "type": "welcome", "protocolVersion": 1, "gatewayVersion": "1.2.3",
                "machineId": "m1" }),
        json!({ "type": "task", "id": "t1", "timeoutMs": 30000,
                "spec": { "kind": "shell", "command": "ls", "cwd": "/tmp",
                          "env": { "TOKEN": "x" } } }),
        json!({ "type": "task", "id": "t2", "timeoutMs": 1000,
                "spec": { "kind": "files", "op": "git-file", "root": "/repo", "path": "a.rs",
                          "against": "HEAD", "maxBytes": 1000 } }),
        json!({ "type": "task", "id": "t3", "timeoutMs": 1000,
                "spec": { "kind": "files", "op": "search", "path": "/repo", "pattern": "x",
                          "ignoreCase": false, "contextLines": 0, "output": "content",
                          "limit": 10 } }),
        json!({ "type": "task", "id": "t4", "timeoutMs": 1000,
                "spec": { "kind": "computer", "action": "left_click", "coordinate": [10, 20],
                          "session": { "id": "s1", "name": "Mia", "color": "#ff8800" } } }),
        json!({ "type": "task", "id": "t5", "timeoutMs": 1000,
                "spec": { "kind": "update", "version": "latest" } }),
        json!({ "type": "resultAck", "id": "t1" }),
        json!({ "type": "cancel", "id": "t1" }),
        json!({ "type": "forwards",
                "forwards": [{ "id": "f1", "port": 4310, "bind": "127.0.0.1" }] }),
        json!({ "type": "channelClose", "channel": 7 }),
        json!({ "type": "ping", "nonce": 9 }),
        json!({ "type": "pong", "nonce": 9 }),
    ];

    let check = format!(
        "{HEADER}\
         // Each message below was parsed and written back by the Rust types, then has to satisfy\n\
         // the generated TypeScript type: `tsc --noEmit -p packages/protocol` checks it.\n\
         import type {{ GatewayMessage, WorkerMessage }} from \"./src/index\";\n\n\
         export const workerMessages = {} satisfies WorkerMessage[];\n\n\
         export const gatewayMessages = {} satisfies GatewayMessage[];\n",
        list::<WorkerMessage>(&worker),
        list::<GatewayMessage>(&gateway),
    );
    fs::write(package().join("check.ts"), check).unwrap();
}

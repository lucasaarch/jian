//! The TypeScript side of the protocol: `packages/protocol/src/index.ts` and `check.ts`.
//!
//! The types themselves are written by ts-rs, in the crate's own `export_bindings_*` tests. This
//! test runs after them (cargo runs a package's test binaries one after another) and adds what
//! ts-rs does not: the index that re-exports every generated type, and `check.ts`, where example
//! messages that Rust serialized must satisfy those types, so `tsc` fails on a shape the Rust
//! side no longer produces. `make protocol-gen` runs both and `make protocol-check` fails on any
//! difference with the committed files.

// clippy.toml excuses `#[test]` bodies, not the helpers they call.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use jian_protocol::client::{ClientMessage, ServerMessage};
use jian_protocol::machine::{GatewayMessage, WorkerMessage};
use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::{Value, json};

const HEADER: &str =
    "// Generated by crates/jian-protocol/tests/typescript.rs. Do not edit this file manually.\n";

fn package() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/protocol")
}

/// The example as Rust reads and writes it: a JSON that does not parse as `T` fails here, and
/// what comes back is what serde emits, which is what the TypeScript type has to describe.
fn through<T: DeserializeOwned + Serialize>(example: &Value) -> Value {
    let value: T = serde_json::from_value(example.clone()).unwrap();
    serde_json::to_value(value).unwrap()
}

fn list<T: DeserializeOwned + Serialize>(examples: &[Value]) -> String {
    let wire: Vec<Value> = examples.iter().map(through::<T>).collect();
    serde_json::to_string_pretty(&wire).unwrap()
}

#[test]
fn the_index_reexports_every_generated_type() {
    let generated = package().join("src/generated");
    let mut names: Vec<String> = fs::read_dir(&generated)
        .unwrap()
        .filter_map(|entry| {
            let name = entry.unwrap().file_name().into_string().unwrap();
            name.strip_suffix(".ts").map(str::to_owned)
        })
        .collect();
    names.sort();
    assert!(
        !names.is_empty(),
        "run the ts-rs export tests first (`make protocol-gen`)"
    );

    let mut index = String::from(HEADER);
    for name in &names {
        writeln!(
            index,
            "export type {{ {name} }} from \"./generated/{name}\";"
        )
        .unwrap();
    }
    fs::write(package().join("src/index.ts"), index).unwrap();
}

